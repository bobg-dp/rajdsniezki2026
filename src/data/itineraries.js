function withNavigation(day) {
  return {
    ...day,
    groups: day.groups.map((group) => ({
      ...group,
      rows: group.rows.map((row) => {
        const placeId =
          placeByCode[row.code] ?? (row.kind === "service" ? "service" : null);
        const place = placeId ? places[placeId] : null;

        return place ? { ...row, ...place } : row;
      }),
    })),
  };
}

const itineraries = {
  ro: [withNavigation(roSunday)],
  rs: [withNavigation(rsSunday)],
  kjs: [withNavigation(kjsSunday)],
};

export function getItinerary(tierKey) {
  return itineraries[tierKey] ?? null;
}
